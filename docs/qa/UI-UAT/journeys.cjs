const {webkit}=require(process.env.BASE_PLAYWRIGHT);
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const baseURL=process.argv[2];
assert.equal(new URL(baseURL).hostname,'127.0.0.1');
const log=path.join(__dirname,'journeys.txt');
fs.writeFileSync(log,'');
let step='launch';
function pass(){fs.appendFileSync(log,step+' PASS\n');}
(async()=>{
 const b=await webkit.launch();
 try{
  const ctx=await b.newContext({baseURL,viewport:{width:768,height:1024}});
  await ctx.route('**/*',r=>new URL(r.request().url()).origin===baseURL?r.continue():r.abort());
  const p=await ctx.newPage();
  step='Guest new PDP session, missing CSRF 403 and valid form adds one SKU';
  await p.goto('/products/fixture-a');
  const add=p.locator('form[action="/cart/items"]');
  assert.ok(await add.locator('[name="_csrf"]').inputValue());
  assert.equal((await ctx.request.post('/cart/items',{form:{variant:'1'}})).status(),403);
  await Promise.all([p.waitForNavigation(),add.locator('button').click()]);
  await p.goto('/cart');
  assert.equal(await p.locator('#quantity-1').inputValue(),'1');
  pass();
  step='Guest cart Back/Forward and server quantity after reload';
  await p.goto('/products');
  await p.goBack();assert.equal(new URL(p.url()).pathname,'/cart');
  await p.goForward();assert.equal(new URL(p.url()).pathname,'/products');
  await p.goBack();await p.reload();assert.equal(await p.locator('#quantity-1').inputValue(),'1');pass();
  step='Keyboard Tab / Shift+Tab on login and visible focus';
  await p.goto('/login');
  await p.locator('#username').focus();await p.keyboard.press('Tab');
  assert.ok(await p.locator('#password').evaluate(e=>document.activeElement===e));
  await p.keyboard.press('Shift+Tab');
  assert.ok(await p.locator('#username').evaluate(e=>document.activeElement===e && e.matches(':focus-visible') && e.getBoundingClientRect().width>0));pass();
  step='Customer session and cart merge persists across reload';
  await p.locator('#username').fill('buyer@example.invalid');
  await p.locator('#password').fill(process.env.CART01_FIXTURE_PASS);
  await Promise.all([p.waitForNavigation(),p.locator('form[action="/login"] button[type=submit]').click()]);
  await p.goto('/cart');assert.equal(await p.locator('#quantity-1').inputValue(),'8');
  await p.reload();assert.equal(await p.locator('#quantity-1').inputValue(),'8');pass();
  const token=async()=>p.locator('input[name="_csrf"]').first().inputValue();
  step='Customer address invalid form has field error';
  await p.goto('/account/addresses/new');
  const fields={tenNguoiNhan:'Fixture',soDienThoai:'0000000000',diaChiChiTiet:'Fixture new address',laMacDinh:'true',_csrf:await token()};
  const invalid=await ctx.request.post('/account/addresses/new',{form:{...fields,soDienThoai:'invalid'}});
  assert.equal(invalid.status(),200);assert.match(await invalid.text(),/aria-invalid="true"/);pass();
  step='Two concurrent customer POSTs at nine addresses yield ten and one default';
  await p.goto('/account/addresses');
  const items=p.locator('.account-address-list > li');
  assert.equal(await items.count(),9);
  const replies=await Promise.all(['A','B'].map(s=>ctx.request.post('/account/addresses/new',{maxRedirects:0,form:{...fields,diaChiChiTiet:'Fixture concurrent '+s}})));
  assert.ok(replies.every(resp=>[302,303].includes(resp.status())));
  await p.reload();assert.equal(await items.count(),10);
  assert.equal(await items.locator('.badge').count(),1);
  assert.equal(await items.filter({hasText:'Fixture concurrent'}).count(),1);pass();
  step='Edit and delete saved address; existing order retains original snapshot';
  await p.goto('/orders/701');assert.match(await p.locator('main').innerText(),/Fixture Address/);
  await p.goto('/account/addresses/1/edit');
  assert.equal((await ctx.request.post('/account/addresses/1/edit',{form:{...fields,_csrf:await token(),diaChiChiTiet:'Fixture changed'}})).status(),200);
  await p.goto('/account/addresses');assert.match(await items.first().innerText()+await items.allTextContents(),/Fixture changed/);
  assert.equal((await ctx.request.post('/account/addresses/1/delete',{form:{_csrf:await token()}})).status(),200);
  await p.reload();assert.equal(await items.count(),9);
  await p.goto('/orders/701');const snapshot=await p.locator('main').innerText();
  assert.match(snapshot,/Fixture Address/);assert.doesNotMatch(snapshot,/Fixture changed/);pass();
 }finally{await b.close();}
})().catch(e=>{fs.appendFileSync(log,step+' FAIL '+e.name+'\n');process.exitCode=1;});
