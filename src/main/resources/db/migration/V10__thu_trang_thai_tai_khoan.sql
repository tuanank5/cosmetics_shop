CREATE TABLE thu_trang_thai_tai_khoan (
    ma_thu BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ma_thao_tac CHAR(36) NOT NULL UNIQUE,
    ma_admin BIGINT NOT NULL,
    ma_nguoi_dung BIGINT NOT NULL,
    mo_khoa BOOLEAN NOT NULL,
    phien_ban_truoc BIGINT NOT NULL,
    ly_do VARCHAR(40) NOT NULL,
    nguoi_nhan VARCHAR(190) NULL,
    thoi_diem DATETIME(6) NOT NULL,
    trang_thai VARCHAR(16) NOT NULL,
    so_lan_gui INT NOT NULL DEFAULT 0,
    gui_tu DATETIME(6) NOT NULL,
    ma_lease CHAR(36) NULL,
    het_lease DATETIME(6) NULL,
    FOREIGN KEY (ma_admin) REFERENCES nguoi_dung(ma_nguoi_dung),
    FOREIGN KEY (ma_nguoi_dung) REFERENCES nguoi_dung(ma_nguoi_dung),
    CHECK (so_lan_gui BETWEEN 0 AND 4),
    CHECK (trang_thai IN ('UNVERIFIED','PENDING','SENDING','SENT','FAILED','UNKNOWN')),
    CHECK ((trang_thai = 'UNVERIFIED') = (nguoi_nhan IS NULL)),
    CHECK ((trang_thai = 'SENDING') = (ma_lease IS NOT NULL)),
    CHECK ((trang_thai = 'SENDING') = (het_lease IS NOT NULL)),
    INDEX ix_thu_den_han (trang_thai, gui_tu, ma_thu),
    INDEX ix_thu_nguoi_dung (ma_nguoi_dung, ma_thu)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
